def render_typescript(v: Vocabulary) -> str:
    def union(name: str, values: list[str]) -> list[str]:
        const = "".join(["_" + c if c.isupper() else c.upper() for c in name]).lstrip("_") + "S"
        body = ", ".join(f"'{value}'" for value in values)
        return [f"export const {const} = [{body}] as const", f"export type {name} = (typeof {const})[number]", ""]

    out = [f"// {HEADER}", "", f"export const VOCABULARY_VERSION = {v.version}", ""]
    out += union("NodeType", list(v.node_types))
    out += union("CoreNodeType", v.core)
    out += union("RelationshipType", list(v.relationship_types))
    for enum_name, spec in v.enums.items():
        out += union(pascal(enum_name), list(spec["values"]))
    out.append("export const NODE_LABELS: Record<NodeType, string> = {")
    out += [f"  {name}: '{spec['label']}'," for name, spec in v.node_types.items()]
    out += ["}", "", "export const LIFE_AREA_LABELS: Record<LifeArea, string> = {"]
    out += [f"  {key}: '{label}'," for key, label in v.enums["life_area"]["values"].items()]
    out += ["}", "", "export const NODE_KINDS: Partial<Record<NodeType, readonly string[]>> = {"]
    for name, spec in v.node_types.items():
        if spec.get("kinds"):
            out.append(f"  {name}: [" + ", ".join(f"'{k}'" for k in spec["kinds"]) + "],")
    out += ["}", ""]
    for name, spec in v.node_types.items():
        out.append(f"export interface {pascal(name)}Attributes {{")
        out += [f"  {field}?: {ts_type(fspec)} | null" for field, fspec in spec.get("fields", {}).items()]
        out += ["}", ""]
    out.append("export const ENDPOINTS: Record<RelationshipType, { from: readonly NodeType[]; to: readonly NodeType[] }> = {")
    for name, spec in v.relationship_types.items():
        from_types = ", ".join(f"'{t}'" for t in v.endpoints(spec["from"]))
        to_types = ", ".join(f"'{t}'" for t in v.endpoints(spec["to"]))
        out.append(f"  {name}: {{ from: [{from_types}], to: [{to_types}] }},")
    out += ["}", ""]
    return "\n".join(out)


