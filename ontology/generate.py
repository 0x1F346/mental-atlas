def outputs(v: Vocabulary) -> dict[Path, str]:
    return {
        ROOT / "backend/atlas/domain/generated/vocabulary.py": render_python(v),
        ROOT / "backend/atlas/db/generated/constraints.py": render_constraints(v),
        ROOT / "backend/atlas/domain/generated/extraction_schema.json": render_extraction_schema(v),
        ROOT / "backend/atlas/domain/generated/vocabulary_prompt.md": render_prompt_block(v),
        ROOT / "web/src/api/generated/vocabulary.ts": render_typescript(v),
        ROOT / "docs/ONTOLOGY.md": render_markdown(v),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    stale: list[Path] = []
    for path, content in outputs(load()).items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        init = path.parent / "__init__.py"
        if path.suffix == ".py" and not init.exists():
            init.write_text("")
        path.write_text(content)
    if stale:
        for path in stale:
            sys.stderr.write(f"stale generated file: {path.relative_to(ROOT)}\n")
        sys.stderr.write("run `make generate`\n")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
