def render_constraints(v: Vocabulary) -> str:
    def enum_values(name: str) -> list[str]:
        return list(v.enums[name]["values"])

    kind_clauses = ["kind IS NULL"]
    for name, spec in v.node_types.items():
        if spec.get("kinds"):
            kind_clauses.append(f"(type = '{name}' AND kind IN ({sql_list(spec['kinds'])}))")
    required = [n for n, s in v.node_types.items() if s.get("kind_required")]
    kind_sql = "(" + " OR ".join(kind_clauses) + ")"
    if required:
        kind_sql += f" AND (type NOT IN ({sql_list(required)}) OR kind IS NOT NULL)"

    checks: dict[str, dict[str, str]] = {
        "sources": {
            "ck_sources_kind": f"kind IN ({sql_list(enum_values('source_kind'))})",
            "ck_sources_status": f"status IN ({sql_list(enum_values('source_status'))})",
        },
        "speakers": {"ck_speakers_role": f"role IS NULL OR role IN ({sql_list(enum_values('speaker_role'))})"},
        "statements": {
            "ck_statements_kind": f"kind IN ({sql_list(enum_values('statement_kind'))})",
            "ck_statements_speaker_role": f"speaker_role IN ({sql_list(enum_values('speaker_role'))})",
        },
        "nodes": {
            "ck_nodes_type": f"type IN ({sql_list(list(v.node_types))})",
            "ck_nodes_kind": kind_sql,
            "ck_nodes_status": f"status IN ({sql_list(enum_values('status'))})",
            "ck_nodes_state": f"state IN ({sql_list(enum_values('record_state'))})",
            "ck_nodes_noticed_by": f"noticed_by <@ ARRAY[{sql_list(enum_values('noticed_by'))}]::text[]",
        },
        "edges": {
            "ck_edges_type": f"type IN ({sql_list(list(v.relationship_types))})",
            "ck_edges_status": f"status IN ({sql_list(enum_values('status'))})",
            "ck_edges_state": f"state IN ({sql_list(enum_values('record_state'))})",
            "ck_edges_noticed_by": f"noticed_by <@ ARRAY[{sql_list(enum_values('noticed_by'))}]::text[]",
        },
        "evidence": {
            "ck_evidence_stance": f"stance IN ({sql_list(enum_values('evidence_stance'))})",
            "ck_evidence_basis": f"basis IN ({sql_list(enum_values('evidence_basis'))})",
        },
        "life_areas": {"ck_life_areas_key": f"key IN ({sql_list(enum_values('life_area'))})"},
    }

    rows: list[str] = []
    for name, spec in v.relationship_types.items():
        for from_type in v.endpoints(spec["from"]):
            for to_type in v.endpoints(spec["to"]):
                rows.append(f"('{name}','{from_type}','{to_type}')")
    values_sql = ",\n            ".join(rows)
    function_sql = f"""CREATE OR REPLACE FUNCTION atlas_check_edge_endpoints() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    from_type text;
    to_type text;
BEGIN
    SELECT type INTO from_type FROM nodes WHERE id = NEW.from_node_id;
    SELECT type INTO to_type FROM nodes WHERE id = NEW.to_node_id;
    IF from_type IS NULL OR to_type IS NULL THEN
        RAISE EXCEPTION 'edge endpoint node not found' USING ERRCODE = 'check_violation';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM (VALUES
            {values_sql}
        ) AS allowed(rel, f, t)
        WHERE allowed.rel = NEW.type AND allowed.f = from_type AND allowed.t = to_type
    ) THEN
        RAISE EXCEPTION 'relationship endpoints not allowed by the vocabulary'
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$"""

    out = [
        f'"""{HEADER}',
        "",
        "Check constraints by table, and the trigger function that enforces relationship",
        "endpoint rules. Migrations apply these; a test compares them with the live database.",
        '"""',
        "",
        f"VOCABULARY_VERSION = {v.version}",
        "",
        "CHECK_CONSTRAINTS: dict[str, dict[str, str]] = {",
    ]
    for table, constraints in checks.items():
        out.append(f'    "{table}": {{')
        for cname, sql in constraints.items():
            out.append(f'        "{cname}": {json.dumps(sql)},')
        out.append("    },")
    out += ["}", "", 'EDGE_ENDPOINT_FUNCTION_SQL = """', function_sql, '"""', ""]
    return "\n".join(out)


