def render_prompt_block(v: Vocabulary) -> str:
    out = [f"<!-- {HEADER} -->", f"Vocabulary version {v.version}.", "", "Concept types:"]
    for name in v.core:
        spec = v.node_types[name]
        line = f"- {name}: {spec['meaning']}"
        if spec.get("kinds"):
            requirement = "required" if spec.get("kind_required") else "optional"
            line += f" Kind ({requirement}): {', '.join(spec['kinds'])}."
        if spec.get("fields"):
            line += " Fields: " + ", ".join(spec["fields"]) + "."
        out.append(line)
    out += ["", "Relationship types (from -> to):"]
    for name, spec in v.relationship_types.items():
        if v.phase(name) != 1:
            continue
        from_types = "any type" if spec["from"] == "any_core" else ", ".join(v.endpoints(spec["from"]))
        to_types = "any type" if spec["to"] == "any_core" else ", ".join(v.endpoints(spec["to"]))
        out.append(f"- {name}: {from_types} -> {to_types}. {spec['meaning']}")
    out += ["", "Life areas: " + ", ".join(v.enums["life_area"]["values"]) + ".", ""]
    return "\n".join(out)


