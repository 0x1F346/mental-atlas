def render_extraction_schema(v: Vocabulary) -> str:
    def enum_values(name: str) -> list[str]:
        return list(v.enums[name]["values"])

    evidence_item = {
        "type": "object",
        "additionalProperties": False,
        "required": ["statement", "stance", "basis"],
        "properties": {
            "statement": {"type": "string", "description": "The id of a statement in this window."},
            "stance": {"type": "string", "enum": enum_values("evidence_stance")},
            "basis": {
                "type": "string",
                "enum": enum_values("evidence_basis"),
                "description": "explicit only when the speaker named the thing; otherwise implied.",
            },
        },
    }
    evidence = {"type": "array", "minItems": 1, "items": evidence_item}
    confidence = {"type": "number", "minimum": 0, "maximum": 1}

    all_kinds = sorted({k for s in v.node_types.values() for k in s.get("kinds", [])})
    attribute_properties: dict[str, Any] = {}
    for name in v.core:
        for field, fspec in v.node_types[name].get("fields", {}).items():
            entry = json_type(fspec)
