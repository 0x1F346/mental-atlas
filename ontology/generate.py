def render_markdown(v: Vocabulary) -> str:
    out = [
        "# Ontology",
        "",
        f"<!-- {HEADER} -->",
        "",
        f"Vocabulary version {v.version}. The source is `ontology/atlas.yaml`; only the owner approves changes to it.",
        "",
        "## Node types",
        "",
        "| Type | Group | Meaning | Kinds | Type-specific fields |",
        "| --- | --- | --- | --- | --- |",
    ]
    for name, spec in v.node_types.items():
        kinds = ", ".join(f"`{k}`" for k in spec.get("kinds", [])) or "None"
        if spec.get("kind_required"):
            kinds += " (required)"
        fields = ", ".join(f"`{f}`" for f in spec.get("fields", {})) or "None"
        out.append(f"| {spec['label']} (`{name}`) | {spec['group']} | {spec['meaning']} | {kinds} | {fields} |")
    out += ["", "## Relationships", "", "| Name | From | To | Meaning | First used |", "| --- | --- | --- | --- | --- |"]
    shorthand = {"any_core": "Any core type", "any_node": "Any node"}
    for name, spec in v.relationship_types.items():
        def side(value: Any) -> str:
            if isinstance(value, str):
                return shorthand[value]
            return ", ".join(v.node_types[t]["label"] for t in value)

        phase = v.phase(name)
        out.append(f"| `{name}` | {side(spec['from'])} | {side(spec['to'])} | {spec['meaning']} | {'V1' if phase == 1 else f'Phase {phase}'} |")
    out += ["", "## Enumerations"]
    for enum_name, spec in v.enums.items():
        out += ["", f"### `{enum_name}`", "", spec["meaning"], ""]
        out += [f"- `{value}`: {meaning}" for value, meaning in spec["values"].items()]
    out.append("")
    return "\n".join(out)


