def render_python(v: Vocabulary) -> str:
    out: list[str] = [
        f'"""{HEADER}"""',
        "",
        "import datetime",
        "from enum import StrEnum",
        "",
        "from pydantic import BaseModel, ConfigDict",
        "",
        f"VOCABULARY_VERSION = {v.version}",
        "",
        "",
        "class NodeType(StrEnum):",
    ]
    out += [f'    {name.upper()} = "{name}"' for name in v.node_types]
    out += ["", "", "class RelationshipType(StrEnum):"]
    out += [f'    {name} = "{name}"' for name in v.relationship_types]
    for enum_name, spec in v.enums.items():
        out += ["", "", f"class {pascal(enum_name)}(StrEnum):", f'    """{spec["meaning"]}"""', ""]
        out += [f'    {value.upper()} = "{value}"' for value in spec["values"]]

    def type_set(names: list[str]) -> str:
        return "frozenset({" + ", ".join(f"NodeType.{n.upper()}" for n in names) + "})"

    out += [
        "",
        "",
        f"CORE_TYPES: frozenset[NodeType] = {type_set(v.core)}",
        f"DERIVED_TYPES: frozenset[NodeType] = {type_set(v.derived)}",
        "",
        "NODE_LABELS: dict[NodeType, str] = {",
    ]
    out += [f'    NodeType.{n.upper()}: "{s["label"]}",' for n, s in v.node_types.items()]
    out += ["}", "", "# Allowed values of nodes.kind, per type. A type missing here has no kinds.", "NODE_KINDS: dict[NodeType, frozenset[str]] = {"]
    for name, spec in v.node_types.items():
        if spec.get("kinds"):
            kinds = ", ".join(f'"{k}"' for k in spec["kinds"])
            out.append(f"    NodeType.{name.upper()}: frozenset({{{kinds}}}),")
    required = [n for n, s in v.node_types.items() if s.get("kind_required")]
    out += ["}", "", f"KIND_REQUIRED: frozenset[NodeType] = {type_set(required)}", ""]
    out += [
        "# Allowed (from, to) node types per relationship.",
        "ENDPOINTS: dict[RelationshipType, tuple[frozenset[NodeType], frozenset[NodeType]]] = {",
    ]
    for name, spec in v.relationship_types.items():
        out.append(f"    RelationshipType.{name}: (")
        out.append(f"        {type_set(v.endpoints(spec['from']))},")
        out.append(f"        {type_set(v.endpoints(spec['to']))},")
        out.append("    ),")
    out += ["}", "", "# The first phase that writes each relationship.", "RELATIONSHIP_PHASE: dict[RelationshipType, int] = {"]
    out += [f"    RelationshipType.{name}: {v.phase(name)}," for name in v.relationship_types]
    context = [n for n, s in v.relationship_types.items() if s.get("context_event")]
    out += [
        "}",
        "",
        "CONTEXT_EVENT_RELATIONSHIPS: frozenset[RelationshipType] = frozenset(",
        "    {" + ", ".join(f"RelationshipType.{n}" for n in context) + "}",
        ")",
    ]

    def attribute_model(class_name: str, owner: str, fields: dict[str, Any]) -> list[str]:
        lines: list[str] = []
        for field, fspec in fields.items():
            if fspec["type"] == "enum":
                enum_name = f"{class_name.removesuffix('Attributes')}{pascal(field)}"
                lines += ["", "", f"class {enum_name}(StrEnum):"]
                lines += [f'    {value.upper()} = "{value}"' for value in fspec["values"]]
        lines += ["", "", f"class {class_name}(BaseModel):", f'    """Type-specific fields of {owner}."""', ""]
        lines.append('    model_config = ConfigDict(extra="forbid")')
        if fields:
            lines.append("")
        for field, fspec in fields.items():
            enum_name = f"{class_name.removesuffix('Attributes')}{pascal(field)}"
            lines.append(f"    {field}: {py_type(fspec, enum_name)} | None = None")
        return lines

    for name, spec in v.node_types.items():
        out += attribute_model(f"{pascal(name)}Attributes", f"a {spec['label']} node", spec.get("fields", {}))
    out += ["", "", "NODE_ATTRIBUTE_MODELS: dict[NodeType, type[BaseModel]] = {"]
    out += [f"    NodeType.{n.upper()}: {pascal(n)}Attributes," for n in v.node_types]
    out.append("}")
    for name, spec in v.relationship_types.items():
        out += attribute_model(f"{pascal(name)}EdgeAttributes", f"a {name} relationship", spec.get("fields", {}))
    out += ["", "", "EDGE_ATTRIBUTE_MODELS: dict[RelationshipType, type[BaseModel]] = {"]
    out += [f"    RelationshipType.{n}: {pascal(n)}EdgeAttributes," for n in v.relationship_types]
    out += ["}", ""]
    return "\n".join(out)


