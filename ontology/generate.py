"""Generate code and docs from ontology/atlas.yaml.

Writes six files (the plan's five outputs, with the model-facing output split in two):

  backend/atlas/domain/generated/vocabulary.py         enums, rule tables, validation models
  backend/atlas/db/generated/constraints.py            database check constraints and the endpoint trigger
  backend/atlas/domain/generated/extraction_schema.json  tool schemas handed to the extraction model
  backend/atlas/domain/generated/vocabulary_prompt.md  the vocabulary block of the extraction prompts
  web/src/api/generated/vocabulary.ts                  TypeScript types
  docs/ONTOLOGY.md                                     readable copy

Run `make generate` to write them and `make generate-check` to fail when they are stale.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "ontology" / "atlas.yaml"
HEADER = "Generated by ontology/generate.py from ontology/atlas.yaml. Do not edit by hand."

FIELD_TYPES = {"text", "date", "boolean", "integer", "enum"}


# ---------------------------------------------------------------------------
# Load and validate
# ---------------------------------------------------------------------------


class Vocabulary:
    def __init__(self, raw: dict[str, Any]) -> None:
        self.version: int = raw["version"]
        self.node_types: dict[str, dict[str, Any]] = raw["node_types"]
        self.relationship_types: dict[str, dict[str, Any]] = raw["relationship_types"]
        self.enums: dict[str, dict[str, Any]] = raw["enums"]
        self.core = [k for k, v in self.node_types.items() if v["group"] == "core"]
        self.derived = [k for k, v in self.node_types.items() if v["group"] == "derived"]
        self.special = [k for k, v in self.node_types.items() if v["group"] == "special"]
        self._validate()

    def endpoints(self, spec: Any) -> list[str]:
        if spec == "any_core":
            return list(self.core)
        if spec == "any_node":
            return [*self.core, *self.derived]
        assert isinstance(spec, list), spec
        return list(spec)

    def phase(self, rel: str) -> int:
        return int(self.relationship_types[rel].get("phase", 1))

    def _validate(self) -> None:
        assert isinstance(self.version, int) and self.version >= 1
        for name, spec in self.node_types.items():
            assert name.islower() and spec["group"] in {"core", "derived", "special"}, name
            assert spec.get("label") and spec.get("meaning"), name
            for field, fspec in spec.get("fields", {}).items():
                assert fspec["type"] in FIELD_TYPES, (name, field)
                assert (fspec["type"] == "enum") == ("values" in fspec), (name, field)
            if spec.get("kind_required"):
                assert spec.get("kinds"), name
        for name, spec in self.relationship_types.items():
            assert name.isupper(), name
            for side in ("from", "to"):
                for node_type in self.endpoints(spec[side]):
                    assert node_type in self.node_types, (name, side, node_type)
            for field, fspec in spec.get("fields", {}).items():
                assert fspec["type"] in FIELD_TYPES, (name, field)
        for name, spec in self.enums.items():
            assert spec.get("meaning") and spec.get("values"), name


def load() -> Vocabulary:
    return Vocabulary(yaml.safe_load(SOURCE.read_text()))


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def pascal(name: str) -> str:
    return "".join(part.capitalize() for part in name.lower().split("_"))


def sql_list(values: list[str]) -> str:
    return ", ".join("'" + v.replace("'", "''") + "'" for v in values)


def py_type(fspec: dict[str, Any], enum_name: str) -> str:
    return {
        "text": "str",
        "date": "datetime.date",
        "boolean": "bool",
        "integer": "int",
        "enum": enum_name,
    }[fspec["type"]]


def ts_type(fspec: dict[str, Any]) -> str:
    if fspec["type"] == "enum":
        return " | ".join(f"'{v}'" for v in fspec["values"])
    return {"text": "string", "date": "string", "boolean": "boolean", "integer": "number"}[
        fspec["type"]
    ]


def json_type(fspec: dict[str, Any]) -> dict[str, Any]:
    if fspec["type"] == "enum":
        return {"type": ["string", "null"], "enum": [*fspec["values"], None]}
    if fspec["type"] == "date":
        return {"type": ["string", "null"], "description": "ISO date, YYYY-MM-DD."}
    return {
        "type": [{"text": "string", "boolean": "boolean", "integer": "integer"}[fspec["type"]], "null"]
    }


